/* ---------------- the case panel ---------------- */
(function () {
  "use strict";
  var UI = {
    ja: { open: "この施策の全体を読む", close: "閉じる", beats: "場面 ／ 届き方 ／ 理由 ／ 効果 ／ 一歩" },
    en: { open: "Read the whole case", close: "Close", beats: "Scene / Reach / Why / Effect / First step" }
  };
  function lang() { return document.documentElement.lang === "en" ? "en" : "ja"; }

  var panel = document.getElementById("casePanel"),
      body = document.getElementById("caseBody"),
      closeBtn = document.getElementById("caseClose"),
      current = null;

  function render() {
    if (!current) return;
    var c = window.CASES[current][lang()];
    body.innerHTML =
      '<p class="caseKicker">' + c.kicker + "</p>" +
      '<h2 class="caseTitle">' + c.title + "</h2>" +
      c.beats.map(function (b, i) {
        return '<div class="caseBeat"><span class="caseNum">0' + (i + 1) + "</span>" +
               "<h3>" + b[0] + "</h3><p>" + b[1] + "</p></div>";
      }).join("");
    closeBtn.textContent = UI[lang()].close;
  }
  function open(id) {
    current = id;
    render();
    panel.hidden = false;
    panel.scrollTop = 0;
    document.body.style.overflow = "hidden";
    closeBtn.focus();
  }
  function close() {
    panel.hidden = true;
    current = null;
    document.body.style.overflow = "";
  }

  /* the buttons take their label from the current language */
  function labelButtons() {
    document.querySelectorAll(".caseBtn").forEach(function (b) {
      b.textContent = (b.dataset[lang()] || UI[lang()].open) + " →";
    });
  }
  labelButtons();
  new MutationObserver(function () { labelButtons(); if (!panel.hidden) render(); })
    .observe(document.documentElement, { attributes: true, attributeFilter: ["lang"] });

  document.addEventListener("click", function (e) {
    var b = e.target.closest(".caseBtn");
    if (b) { e.preventDefault(); open(b.dataset.case); return; }
    if (e.target === panel || e.target === closeBtn) close();
  });
  document.addEventListener("keydown", function (e) {
    if (e.key === "Escape" && !panel.hidden) close();
  });
})();
